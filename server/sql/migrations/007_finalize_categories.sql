-- 안전장치: 옛 데이터 복사본 (확인 후 DROP TABLE SHELTER_OLD_BACKUP 으로 삭제)
CREATE TABLE SHELTER_OLD_BACKUP AS
  SELECT * FROM SHELTER WHERE SOURCE_ID NOT LIKE 'DSSP%';

-- 1) 기존 지진 실내구호소 이름 변경
UPDATE SHELTER SET CATEGORY = 'EARTHQUAKE_INDOOR' WHERE CATEGORY = 'EARTHQUAKE';

-- 2) 옛 민방위·해일 삭제 (새 데이터는 SOURCE_ID가 DSSP로 시작)
DELETE FROM SHELTER
 WHERE CATEGORY IN ('CIVIL_DEFENSE', 'TSUNAMI') AND SOURCE_ID NOT LIKE 'DSSP%';

COMMIT;

-- 3) 제약조건에서 옛 값 제거
ALTER TABLE SHELTER DROP CONSTRAINT CK_SHELTER_CATEGORY;
ALTER TABLE SHELTER ADD CONSTRAINT CK_SHELTER_CATEGORY CHECK (CATEGORY IN (
  'CIVIL_DEFENSE', 'EARTHQUAKE_OUTDOOR', 'EARTHQUAKE_INDOOR',
  'TSUNAMI', 'HEAT_SHELTER', 'COLD_SHELTER'
));