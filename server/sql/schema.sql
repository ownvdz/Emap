-- 현재 DB 전체 구조 (최신본). 새 DB를 처음 만들 때만 실행.
CREATE TABLE SHELTER (
  SHELTER_ID        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  SOURCE_ID         VARCHAR2(50) UNIQUE,
  CATEGORY          VARCHAR2(20) DEFAULT 'CIVIL_DEFENSE' NOT NULL,
  NAME              VARCHAR2(300),
  SHELTER_TYPE      VARCHAR2(100),
  CAPACITY          NUMBER,
  AREA_SQM          NUMBER,
  DETAIL_ADDRESS    VARCHAR2(300),
  ROAD_ADDRESS      VARCHAR2(300),
  LEGAL_DONG_CODE   VARCHAR2(20),
  NORMAL_USE_TYPE   VARCHAR2(300),
  IS_OPEN           VARCHAR2(10),
  MANAGE_AGENCY     VARCHAR2(300),
  LATITUDE          NUMBER(10,7),
  LONGITUDE         NUMBER(10,7),
  GEOCODE_STATUS    VARCHAR2(20) DEFAULT 'PENDING',
  RAW_DATA          CLOB,
  UPDATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT CK_SHELTER_CATEGORY CHECK (CATEGORY IN ('CIVIL_DEFENSE', 'EARTHQUAKE', 'TSUNAMI'))
);

CREATE INDEX IDX_SHELTER_GEOCODE ON SHELTER (GEOCODE_STATUS);
CREATE INDEX IDX_SHELTER_LATLNG ON SHELTER (LATITUDE, LONGITUDE);
CREATE INDEX IDX_SHELTER_CATEGORY ON SHELTER (CATEGORY);