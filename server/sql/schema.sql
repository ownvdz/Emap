CREATE TABLE SHELTER (
  SHELTER_ID        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  SOURCE_ID         VARCHAR2(50) UNIQUE,
  SHELTER_TYPE      VARCHAR2(100),
  CAPACITY          NUMBER,
  AREA_SQM          NUMBER,
  DETAIL_ADDRESS    VARCHAR2(300),
  ROAD_ADDRESS      VARCHAR2(300),
  LEGAL_DONG_CODE   VARCHAR2(20),
  NORMAL_USE_TYPE   VARCHAR2(100),
  IS_OPEN           VARCHAR2(10),
  MANAGE_AGENCY     VARCHAR2(200),
  LATITUDE          NUMBER(10,7),
  LONGITUDE         NUMBER(10,7),
  GEOCODE_STATUS    VARCHAR2(20) DEFAULT 'PENDING',
  RAW_DATA          CLOB,
  UPDATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP
);